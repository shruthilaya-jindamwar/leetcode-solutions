
// Number
let rollNum = 123
console.log(rollNum)
// 123


// String
let studentName = 'Shru Jind'
console.log(studentName)
// Shru Jind

// Boolean
let isTakingCoaching = true
console.log(isTakingCoaching)
// true

// ===========

// Object  ( key, value pairs )
let student = {
    rollNum: 123,
    studentName: 'Shru Jind',
    isTakingCoaching: true
}
console.log(student)
// { rollNum: 123, studentName: 'Shru Jind', isTakingCoaching: true }


// ===========

// Array of numbers
let marks  = [ 100, 90, 50,  36 ]
console.log(marks)
// [ 100, 90, 50, 36 ]

// Array of strings
let names  = [ 'Sru', 'Ram', 'Lax' ]
console.log(names)
// [ 'Sru', 'Ram', 'Lax' ]

let passedArray = [ true, false]
console.log(passedArray)
// [ true, false ]

